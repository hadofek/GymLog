String buildBodySvg({
  required Map<String, int> counts,
  required int totalCount,
  required bool isDark,
}) {
  final bodyBase = isDark ? '#1E2436' : '#D4D8E4';
  final muscleBase = isDark ? '#2C3248' : '#C8CCDA';

  final sb = StringBuffer();
  sb.write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1460 1360">',
  );

  // Front body
  for (final entry in _front.entries) {
    final slug = entry.key;
    final paths = entry.value;
    final group = _frontSlug[slug];
    final fill = _resolveFill(group, counts, totalCount, bodyBase, muscleBase);
    final opacity = _resolveOpacity(group, counts, totalCount);
    sb.write('<g fill="$fill" fill-opacity="$opacity">');
    _appendPaths(sb, paths);
    sb.write('</g>');
  }

  // Back body
  for (final entry in _back.entries) {
    final slug = entry.key;
    final paths = entry.value;
    final group = _backSlug[slug];
    final fill = _resolveFill(group, counts, totalCount, bodyBase, muscleBase);
    final opacity = _resolveOpacity(group, counts, totalCount);
    sb.write('<g fill="$fill" fill-opacity="$opacity">');
    _appendPaths(sb, paths);
    sb.write('</g>');
  }

  // Labels
  final labelColor = isDark ? '#5C7090' : '#8898B8';
  sb.write(
    '<text x="365" y="1352" text-anchor="middle" fill="$labelColor" '
    'font-size="22" font-weight="700" letter-spacing="10" font-family="sans-serif">FRONT</text>',
  );
  sb.write(
    '<text x="1090" y="1352" text-anchor="middle" fill="$labelColor" '
    'font-size="22" font-weight="700" letter-spacing="10" font-family="sans-serif">BACK</text>',
  );

  sb.write('</svg>');
  return sb.toString();
}

String _resolveFill(
  String? group,
  Map<String, int> counts,
  int totalCount,
  String bodyBase,
  String muscleBase,
) {
  if (group == null) return bodyBase;
  final count = counts[group] ?? 0;
  if (count == 0 || totalCount == 0) return muscleBase;
  // share = fraction of total training volume this muscle represents
  return _heatHex(count / totalCount);
}

double _resolveOpacity(
  String? group,
  Map<String, int> counts,
  int totalCount,
) {
  if (group == null) return 1.0;
  final count = counts[group] ?? 0;
  if (count == 0 || totalCount == 0) return 1.0;
  return 1.0;
}

void _appendPaths(StringBuffer sb, Map<String, List<String>> paths) {
  for (final side in const ['left', 'right', 'common']) {
    final list = paths[side];
    if (list == null) continue;
    for (final d in list) {
      sb.write('<path d="$d"/>');
    }
  }
}
